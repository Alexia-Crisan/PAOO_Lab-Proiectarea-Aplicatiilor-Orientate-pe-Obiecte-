#pragma once
#include <iostream>
#include <string>

// ===========================================================
// Item 5: Know what functions C++ silently writes and calls.
// ===========================================================

class AutoGenerated
{
public:
    std::string label = "Default";
    // NICIUN constructor / operator= / destructor, dar exista generate de compilator
};

// Exceptie: pentru clase cu membri REFERINTA sau CONST, compilatorul NU poate genera operator=
class UncopyableByRef
{
    std::string &nameRef; // referinta
    const int id;         // constanta

public:
    UncopyableByRef(std::string &n, int i) : nameRef(n), id(i) {}
};

// ===========================================================
// Item 6: Explicitly disallow the use of compiler-generated
//         functions you do not want.
// ===========================================================

// Varianta MODERNA: '= delete'
class ModernUncopyable
{
public:
    ModernUncopyable() = default;

    ModernUncopyable(const ModernUncopyable &) = delete;
    ModernUncopyable &operator=(const ModernUncopyable &) = delete;

    void info() const { std::cout << "[Item 6] ModernUncopyable exista, dar nu poate fi copiat.\n"; }
};

// Varianta CLASICA (cartea lui Meyers)
class LegacyUncopyable
{
protected:
    LegacyUncopyable() = default;
    ~LegacyUncopyable() = default;

private:
    LegacyUncopyable(const LegacyUncopyable &);            // doar declarata
    LegacyUncopyable &operator=(const LegacyUncopyable &); // doar declarata
};

// Orice clasa care mosteneste (privat) din LegacyUncopyable devine automat necopiabila.
class NonCopyableResource : private LegacyUncopyable
{
public:
    NonCopyableResource() = default;

    void info() const { std::cout << "[Item 6] NonCopyableResource exista, dar nu poate fi copiat.\n"; }
};