#pragma once
#include <iostream>
#include <string>

// Item 5: Know what functions C++ silently writes and calls.
// Compiler automatically generates default ctor, copy ctor, copy assignment operator, and dtor if needed.

class AutoGenerated
{
public:
    std::string label = "Default";
};

// C++ will NOT generate operator= if class contains const members or references.
class UncopyableByRef
{
    std::string &nameRef; // Reference member prevents compiler-generated copy assignment
    const int id;         // const member prevents compiler-generated copy assignment

public:
    UncopyableByRef(std::string &n, int i) : nameRef(n), id(i) {}
};

// Item 6: Explicitly disallow the use of compiler-generated functions you do not want.

// Modern Way: Use of delete
class ModernUncopyable
{
public:
    ModernUncopyable() = default;

    // explicitly deleted copy operations
    ModernUncopyable(const ModernUncopyable &) = delete;
    ModernUncopyable &operator=(const ModernUncopyable &) = delete;
};

// Legacy Way: Inherit from an Uncopyable base class with private copy operations
class LegacyUncopyable
{
protected:
    LegacyUncopyable() = default;
    ~LegacyUncopyable() = default;

private:
    LegacyUncopyable(const LegacyUncopyable &);
    LegacyUncopyable &operator=(const LegacyUncopyable &);
};

class NonCopyableResource : private LegacyUncopyable
{
public:
    NonCopyableResource() = default;
};